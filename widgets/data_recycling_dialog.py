import os

from qgis.PyQt import uic
from qgis.PyQt import QtWidgets
from qgis.PyQt.QtGui import QIcon
from .confirm_action_dialog import ConfirmActionDialog
from ..utils import string_format
from ..models.user_settings import UserSettings
from ..paths import icon_path

# This loads your .ui file so that PyQt can populate your plugin with the elements from Qt Designer
FORM_CLASS, _ = uic.loadUiType(
    os.path.join(
        os.path.dirname(__file__),
        'data_recycling_dialog_base.ui'),
    from_imports=True,
    import_from='mdi_curitiba')

class DataRecyclingDialog(QtWidgets.QDialog, FORM_CLASS):
    def __init__(self, user_settings: UserSettings, parent=None):
        """Constructor."""
        super(DataRecyclingDialog, self).__init__(parent)
        # Set up the user interface from Designer through FORM_CLASS.
        # After self.setupUi() you can access any designer object by doing
        # self.<objectname>, and you can use autoconnect slots - see
        # http://qt-project.org/doc/qt-4.8/designer-using-a-ui-file.html
        # #widgets-and-dialogs-with-auto-connect
        self.setupUi(self)
        self.setWindowIcon(QIcon(icon_path('aiG-icon')))
        self.user_settings = user_settings

        self.accepted.connect(self.update_recycling_options)

        self.prepare_block_checkBox()
        self.prepare_site_plan_checkBox()
        self.prepare_street_checkBox()
        self.prepare_district_checkBox()
        self.prepare_corner_street_checkBox()

    def update_recycling_options(self):

        self.user_settings.recycle_block = self.block_checkBox.isChecked()
        self.user_settings.recycle_site_plan = self.site_plan_checkBox.isChecked()
        self.user_settings.recycle_street = self.street_checkBox.isChecked()
        self.user_settings.recycle_district = self.district_checkBox.isChecked()
        self.user_settings.recycle_corner_street = self.corner_street_checkBox.isChecked()

    def reject(self):

        confirmed = ConfirmActionDialog(self).exec_()

        if confirmed:
            super().reject()

    def prepare_block_checkBox(self):

        self.block_checkBox.setText(f"Quadra: {self.user_settings.last_block}")
        self.block_checkBox.setChecked(self.user_settings.recycle_block)

    def prepare_site_plan_checkBox(self):

        site_plan, code = self.user_settings.last_site_plan
        self.site_plan_checkBox.setText(f"Planta: {site_plan}" + (f" ({code})" if code else ""))
        self.site_plan_checkBox.setChecked(self.user_settings.recycle_site_plan)

    def prepare_street_checkBox(self):

        street, code = self.user_settings.last_street
        self.street_checkBox.setText(f"Rua: {string_format.format_name(street)}" + (f" ({code})" if code else ""))
        self.street_checkBox.setChecked(self.user_settings.recycle_street)

    def prepare_district_checkBox(self):

        self.district_checkBox.setText(f"Bairro: {string_format.format_name(self.user_settings.last_district)}")
        self.district_checkBox.setChecked(self.user_settings.recycle_district)

    def prepare_corner_street_checkBox(self):

        corner_street, code = self.user_settings.last_corner_street
        self.corner_street_checkBox.setText(f"Rua da Esquina: {string_format.format_name(corner_street)}" + (f" ({code})" if code else ""))
        self.corner_street_checkBox.setChecked(self.user_settings.recycle_corner_street)
